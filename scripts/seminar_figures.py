# ---------------------------------------------------------------------------
# 2. law of large numbers: PDMP paths against the fluid ODE
# ---------------------------------------------------------------------------
def simulate_path(N, p, B, n0, x0, T, rng):
    nstar = int(np.floor(p / C))
    n, x, t = n0, x0, 0.0
    ts, ns, xs = [t], [n], [x]
    while t < T:
        r = p - n * C
        at0 = x <= 1e-12 and r < 0
        atB = x >= B - 1e-12 and r > 0
        up = (N - n) * LAM
        down = NU * p / C if at0 else n * NU
        R = up + down
        tau = rng.exponential(1.0 / R)
        if at0 or atB or r == 0:
            hit = np.inf
        elif r > 0:
            hit = (B - x) / r
        else:
            hit = x / (-r)
        if hit < tau:
            t += hit
            x = B if r > 0 else 0.0
            ts.append(t); ns.append(n); xs.append(x)
            continue
        t += tau
        if not (at0 or atB):
            x = min(B, max(0.0, x + r * tau))
        ts.append(t); ns.append(n); xs.append(x)
        n = n + 1 if rng.random() * R < up else n - 1
        ts.append(t); ns.append(n); xs.append(x)
    return np.array(ts), np.array(ns), np.array(xs)


def fluid_path(pbar, bbar, n0, x0, T, dt=1e-4):
    n, x = n0, x0
    out = [(0.0, n, x)]
    for k in range(int(T / dt)):
        if x <= 1e-12 and C * n > pbar:
            dn, dx = LAM * (1 - n) - NU * pbar / C, 0.0
        elif x >= bbar - 1e-12 and C * n < pbar:
            dn, dx = LAM - GAM * n, 0.0
        else:
            dn, dx = LAM - GAM * n, pbar - C * n
        n += dt * dn
        x = min(bbar, max(0.0, x + dt * dx))
        if k % 50 == 0:
            out.append(((k + 1) * dt, n, x))
    return np.array(out)


def thin(t, y, T, m=1500):
    """Keep about m points of a step path, for a lighter pgfplots file."""
    sel = t <= T
    t, y = t[sel], y[sel]
    if len(t) > m:
        keep = np.unique(np.linspace(0, len(t) - 1, m).astype(int))
        t, y = t[keep], y[keep]
    return " ".join(f"({a:.4f},{b:.4f})" for a, b in zip(t, y))


def fig_lln(case="under"):
    """PDMP paths against the fluid ODE, for round values of pbar. N pbar / c is then an
    integer, so one mode has zero drift; the simulation handles it (x stays put)."""
    if case == "under":
        pbar, bbar, n0, x0, T, fname = 0.2, 0.2, 0.05, 0.06, 5.0, "fluid_lln.tex"
    else:
        pbar, bbar, n0, x0, T, fname = 0.4, 0.2, 0.7, 0.15, 4.0, "fluid_lln_over.tex"
    rng = np.random.default_rng(2026)
    fl = fluid_path(pbar, bbar, n0, x0, T)
    nT = 1 - NU * pbar / (LAM * C)
    plots_n, plots_x = [], []
    grid = np.linspace(0, T - 1e-3, 400)
    jf = np.minimum(np.searchsorted(fl[:, 0], grid), len(fl) - 1)
    for N, col in [(50, "gray!60, thin"), (500, "rojito!85, semithick")]:
        # a typical run: among 9 runs, the one with the median distance to the fluid path
        runs = []
        for _ in range(9):
            ts, ns, xs = simulate_path(N, N * pbar, N * bbar, int(round(N * n0)), N * x0, T, rng)
            i = np.searchsorted(ts, grid, side="right") - 1
            dist = max(np.max(np.abs(ns[i] / N - fl[jf, 1])), np.max(np.abs(xs[i] / N - fl[jf, 2])) / bbar)
            runs.append((dist, ts, ns, xs))
        runs.sort(key=lambda r: r[0])
        _, ts, ns, xs = runs[len(runs) // 2]
        plots_n.append(rf"\addplot[{col}, const plot] coordinates {{{thin(ts, ns / N, T)}}};" + "\n" + rf"\addlegendentry{{$N={N}$}}")
        plots_x.append(rf"\addplot[{col}] coordinates {{{thin(ts, xs / N, T)}}};")
        print("lln path", case, N, "final n/N", ns[-1] / N, "final x/N", xs[-1] / N)
    fn = " ".join(f"({a:.4f},{b:.4f})" for a, b in zip(fl[:, 0], fl[:, 1]))
    fx = " ".join(f"({a:.4f},{b:.4f})" for a, b in zip(fl[:, 0], fl[:, 2]))
    if case == "under":
        nticks, nlabels, nmax = f"0,{RHO},{nT:.2f}", r"0,$\rho$,$\bar n_T$", 0.75
        legpos, leganchor = "(0.03,0.97)", "north west"
    else:
        nticks, nlabels, nmax = f"0,{RHO},1", r"0,$\rho$,1", 1.0
        legpos, leganchor = "(0.97,0.97)", "north east" 
    body = rf"""%% PDMP paths (n/N, x/N) against the fluid ODE ({case}-provisioned); lambda={LAM}, nu={NU}, c={C}, pbar={pbar}, bbar={bbar},
%% start (nbar, xbar) = ({n0}, {x0}); generated by scripts/seminar_figures.py
\begin{{tikzpicture}}
\begin{{groupplot}}[group style={{group size=2 by 1, horizontal sep=1.6cm}},
  width=0.5\textwidth, height=0.42\textwidth, xmin=0, xmax={T}, grid=major, grid style={{gray!25}},
  xlabel={{time}}, tick label style={{font=\footnotesize}}, label style={{font=\footnotesize}}]
\nextgroupplot[ylabel={{$n(t)/N$}}, ymin=0, ymax={nmax}, ytick={{{nticks}}}, yticklabels={{{nlabels}}},
  legend style={{at={{{legpos}}}, anchor={leganchor}, legend columns=1, font=\tiny, draw=none, fill=white, fill opacity=0.6, text opacity=1}},
  legend image post style={{line width=1.3pt}}]
\addplot[azulcito, line width=2pt] coordinates {{{fn}}};
\addlegendentry{{fluid ODE}}
{chr(10).join(plots_n)}
\nextgroupplot[ylabel={{$x(t)/N$}}, ymin=-0.01, ymax={bbar+0.02}, ytick={{0,{bbar}}}, yticklabels={{0,$\bar b$}}]
\addplot[azulcito, line width=2pt] coordinates {{{fx}}};
{chr(10).join(plots_x)}
\end{{groupplot}}
\end{{tikzpicture}}
"""
    open(os.path.join(OUT, fname), "w").write(body)


def fig_diffusion(N=2000, beta=0.5, b=1.0, T=10.0, seed=2):
    """One path under the diffusion scaling: xi = (n - N rho)/sigma_N, xhat = x/(c sigma_N),
    with refill p = c N rho + beta c sigma_N and quota B = b c sigma_N."""
    sig = np.sqrt(N * RHO * (1 - RHO))
    p, B = C * N * RHO + beta * C * sig, b * C * sig
    rng = np.random.default_rng(seed)
    ts, ns, xs = simulate_path(N, p, B, int(round(N * RHO)), B / 2, T, rng)
    xi = (ns - N * RHO) / sig
    xh = xs / (C * sig)
    dt = np.diff(ts)
    print(f"diffusion path: N={N} beta={beta} b={b}  empty {dt[xs[:-1] <= 1e-9].sum()/T:.3f}  full {dt[xs[:-1] >= B - 1e-9].sum()/T:.3f}")
    body = rf"""%% One path under the diffusion scaling: N={N}, lambda={LAM}, nu={NU}, c={C}, beta={beta}, b={b}
%% generated by scripts/seminar_figures.py
\begin{{tikzpicture}}
\begin{{groupplot}}[group style={{group size=1 by 2, vertical sep=0.3cm, xlabels at=edge bottom, xticklabels at=edge bottom}},
  width=\textwidth, height=0.56\textwidth, xmin=0, xmax={T}, grid=major, grid style={{gray!25}},
  tick label style={{font=\footnotesize}}, label style={{font=\footnotesize}}]
\nextgroupplot[ylabel={{$\xi(t)$}}, ymin=-3.2, ymax=3.2, ytick={{-2,{beta},2}}, yticklabels={{$-2$,$\beta$,$2$}}]
\addplot[dashed, rojito, thick, domain=0:{T}] {{{beta}}};
\addplot[azulcito, const plot, thin] coordinates {{{thin(ts, xi, T, 3000)}}};
\nextgroupplot[ylabel={{$\hat x(t)$}}, xlabel={{time}}, ymin=-0.1, ymax={b+0.15}, ytick={{0,{b}}}, yticklabels={{$0$,$b$}}]
\addplot[verdecito!70!black, thick] coordinates {{{thin(ts, xh, T, 3000)}}};
\end{{groupplot}}
\end{{tikzpicture}}
"""
    open(os.path.join(OUT, "diffusion_path.tex"), "w").write(body)


