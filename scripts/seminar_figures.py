# ---------------------------------------------------------------------------
# 2. law of large numbers: PDMP paths against the fluid ODE
# ---------------------------------------------------------------------------
def simulate_path(N, p, B, n0, x0, T, rng):
    nstar = int(np.floor(p / C))
    n, x, t = n0, x0, 0.0
    ts, ns, xs = [t], [n], [x]
    while t < T:
        r = p - n * C
        at0 = x <= 1e-12 and r < 0
        atB = x >= B - 1e-12 and r > 0
        up = (N - n) * LAM
        down = NU * p / C if at0 else n * NU
        R = up + down
        tau = rng.exponential(1.0 / R)
        if at0 or atB or r == 0:
            hit = np.inf
        elif r > 0:
            hit = (B - x) / r
        else:
            hit = x / (-r)
        if hit < tau:
            t += hit
            x = B if r > 0 else 0.0
            ts.append(t); ns.append(n); xs.append(x)
            continue
        t += tau
        if not (at0 or atB):
            x = min(B, max(0.0, x + r * tau))
        ts.append(t); ns.append(n); xs.append(x)
        n = n + 1 if rng.random() * R < up else n - 1
        ts.append(t); ns.append(n); xs.append(x)
    return np.array(ts), np.array(ns), np.array(xs)


def fluid_path(pbar, bbar, n0, x0, T, dt=1e-4):
    n, x = n0, x0
    out = [(0.0, n, x)]
    for k in range(int(T / dt)):
        if x <= 1e-12 and C * n > pbar:
            dn, dx = LAM * (1 - n) - NU * pbar / C, 0.0
        elif x >= bbar - 1e-12 and C * n < pbar:
            dn, dx = LAM - GAM * n, 0.0
        else:
            dn, dx = LAM - GAM * n, pbar - C * n
        n += dt * dn
        x = min(bbar, max(0.0, x + dt * dx))
        if k % 50 == 0:
            out.append(((k + 1) * dt, n, x))
    return np.array(out)


def thin(t, y, T, m=1500):
    """Keep about m points of a step path, for a lighter pgfplots file."""
    sel = t <= T
    t, y = t[sel], y[sel]
    if len(t) > m:
        keep = np.unique(np.linspace(0, len(t) - 1, m).astype(int))
        t, y = t[keep], y[keep]
    return " ".join(f"({a:.4f},{b:.4f})" for a, b in zip(t, y))


