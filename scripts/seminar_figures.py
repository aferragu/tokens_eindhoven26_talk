"""
Figures added for the Seminario ML+DE version of the talk.

1. Stationary solution for two plans (over- and under-provisioned), from the balance
   equations discretised on a grid in x (upwind: x moves one grid step at rate |r_n|/h).
   Outputs, per plan:  figuras/stat_<case>_x.tex  (distribution function of x, showing the atoms)
                       figuras/stat_<case>_n.tex  (law of n against the binomial law pi)
2. Law of large numbers: PDMP paths n/N and x/N for N = 50, 500 against the fluid ODE.
   For each N, the plotted path is the run with the median distance to the fluid path among 9 runs.
   Outputs: figuras/fluid_lln.tex (under-provisioned), figuras/fluid_lln_over.tex (over-provisioned)

Model: N agents, activation rate lam, completion rate nu = mu c while tokens remain;
quota x in [0,B], refill p, drift r_n = p - n c; throttled completions at mu p on {x=0, n c > p}.

3. One path under the diffusion scaling (N = 2000, beta = 0.5, b = 1). Output: figuras/diffusion_path.tex

Run:  python3 seminar_figures.py
"""
import os
import numpy as np
import scipy.sparse as sp
import scipy.sparse.linalg as spla
from math import comb

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "figuras")
LAM, NU, C = 1.0, 3.0, 1.0
GAM = LAM + NU
RHO = LAM / GAM


# ---------------------------------------------------------------------------
# 1. stationary solution on a grid
# ---------------------------------------------------------------------------
def stationary_grid(N, p, B, K):
    h = B / K
    nstar = int(np.floor(p / C))
    S = (N + 1) * (K + 1)
    idx = lambda n, k: n * (K + 1) + k
    rows, cols, vals = [], [], []
    for n in range(N + 1):
        r = p - n * C
        for k in range(K + 1):
            i = idx(n, k)
            if n < N:
                rows.append(i); cols.append(idx(n + 1, k)); vals.append((N - n) * LAM)
            if n > 0:
                rate = NU * p / C if (k == 0 and n > nstar) else n * NU
                rows.append(i); cols.append(idx(n - 1, k)); vals.append(rate)
            if r > 0 and k < K:
                rows.append(i); cols.append(idx(n, k + 1)); vals.append(r / h)
            if r < 0 and k > 0:
                rows.append(i); cols.append(idx(n, k - 1)); vals.append(-r / h)
    Q = sp.csr_matrix((vals, (rows, cols)), shape=(S, S))
    Q = Q - sp.diags(np.asarray(Q.sum(axis=1)).ravel())
    A = Q.T.tolil()
    A[0, :] = np.ones(S)
    rhs = np.zeros(S); rhs[0] = 1.0
    pi = spla.spsolve(A.tocsc(), rhs)
    return pi.reshape(N + 1, K + 1), nstar


