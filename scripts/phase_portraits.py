"""
Phase portraits of the fluid limit of the token-quota model.

Fluid scaling: p = N pbar, B = N bbar, nbar = n/N, xbar = x/N.
  interior  (0 < xbar < bbar):   nbar' = lam (1 - nbar) - nu nbar,   xbar' = pbar - c nbar
  full      (xbar = bbar, c nbar < pbar):  xbar' = 0, nbar as in the interior
  empty     (xbar = 0,    c nbar > pbar):  xbar' = 0, nbar' = lam (1 - nbar) - mu pbar   (throttled; mu = nu / c)

Writes ../figuras/phase_over.tex and ../figuras/phase_under.tex (pgfplots),
with xbar on the horizontal axis and nbar on the vertical axis.
Run:  python3 phase_portraits.py
"""
import os
import numpy as np

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "figuras")

LAM, NU, C = 1.0, 3.0, 1.0
GAM = LAM + NU
RHO = LAM / GAM
BBAR = 0.2


def field(n, x, pbar):
    """Fluid vector field, including the sticky boundaries and the throttle."""
    eps = 1e-12
    if x <= eps and C * n > pbar:            # empty and draining: throttled
        return LAM * (1 - n) - NU * pbar / C, 0.0
    if x >= BBAR - eps and C * n < pbar:     # full and filling: refill wasted
        return LAM - GAM * n, 0.0
    return LAM - GAM * n, pbar - C * n


def trajectory(n0, x0, pbar, T=6.0, dt=2e-4):
    n, x = n0, x0
    pts = [(n, x)]
    for k in range(int(T / dt)):
        dn, dx = field(n, x, pbar)
        n += dt * dn
        x = min(BBAR, max(0.0, x + dt * dx))
        if k % 20 == 0:
            pts.append((n, x))
    pts.append((n, x))
    # thin out points that barely move (sitting at equilibrium)
    out = [pts[0]]
    for q in pts[1:]:
        if abs(q[0] - out[-1][0]) / 1.0 + abs(q[1] - out[-1][1]) / BBAR > 4e-3:
            out.append(q)
    return out


def quiver(pbar, nx=6, ny=11):
    """Arrows on a grid; returned as (x, n, dx, dn), i.e. already transposed."""
    rows = []
    for n in np.linspace(0.05, 0.95, ny):
        for x in np.linspace(0.02, BBAR - 0.02, nx):
            dn, dx = LAM - GAM * n, pbar - C * n
            # direction in screen units (axes: xbar in [0,BBAR] horizontal, nbar in [0,1] vertical)
            sx, sn = dx / BBAR, dn / 1.0
            L = np.hypot(sx, sn)
            if L < 1e-9:
                continue
            ell = 0.045                       # arrow length, as a fraction of the axis box
            rows.append((x, n, ell * sx / L * BBAR, ell * sn / L * 1.0))
    return rows


def coords(pts):
    """Trajectory points (n, x) written transposed as (x, n)."""
    return " ".join(f"({b:.5f},{a:.4f})" for a, b in pts)


def panel(pbar, starts, fname, title):
    thr = pbar / C
    over = pbar > C * RHO
    neq = RHO if over else 1 - NU * pbar / (LAM * C)
    xeq = BBAR if over else 0.0
    q = quiver(pbar)
    qrows = "\n".join(f"{a:.4f} {b:.4f} {c_:.6f} {d:.5f}" for a, b, c_, d in q)
    trajs = []
    for (n0, x0) in starts:
        tr = trajectory(n0, x0, pbar)
        trajs.append(
            rf"\addplot[azulcito, very thick, postaction={{decorate}}, decoration={{markings, mark=at position 0.22 with {{\arrow{{stealth}}}}, mark=at position 0.6 with {{\arrow{{stealth}}}}}}] coordinates {{{coords(tr)}}};"
            + "\n" + rf"\node[circle, fill=azulcito, inner sep=1.3pt] at (axis cs:{x0},{n0}) {{}};")
    if over:
        yticks = f"0,{RHO},{thr},1"
        yticklabels = r"0,$\rho$,$\frac{\bar p}{c}$,1"
        eqnode = rf"\node[font=\footnotesize, anchor=west] at (axis cs:{BBAR+0.006},{RHO}) {{$(\bar b,\rho)$}};"
        extra = ""
    else:
        yticks = f"0,{thr},{RHO},{neq},1"
        yticklabels = r"0,$\frac{\bar p}{c}$,$\rho$,$\bar n_T$,1"
        eqnode = ""
        extra = (rf"\draw[-stealth, very thick, rojito] (axis cs:0.022,{RHO+0.03}) -- node[right, font=\scriptsize] {{slides}} (axis cs:0.022,{neq-0.04});")
    body = rf"""%% Fluid phase portrait (x horizontal, n vertical, as in the state-space picture)
%% lambda={LAM}, nu={NU}, c={C}, rho={RHO:.3f}, pbar={pbar}, bbar={BBAR}; generated by scripts/phase_portraits.py
\begin{{tikzpicture}}
\begin{{axis}}[width=0.9\textwidth, height=0.95\textwidth, xmin=-0.006, xmax={BBAR+0.006}, ymin=0, ymax=1,
  axis lines=box, xlabel={{tokens left $\bar x$}}, ylabel={{active fraction $\bar n$}},
  xtick={{0,{BBAR}}}, xticklabels={{0,$\bar b$}},
  ytick={{{yticks}}}, yticklabels={{{yticklabels}}},
  title={{{title}}}, title style={{font=\small}},
  tick label style={{font=\footnotesize}}, label style={{font=\footnotesize}}, clip=false]
% regions: filling (below pbar/c) and draining (above)
\fill[verdecito!8] (axis cs:0,0) rectangle (axis cs:{BBAR},{thr});
\fill[rojito!6] (axis cs:0,{thr}) rectangle (axis cs:{BBAR},1);
\draw[dashed, gray] (axis cs:0,{thr}) -- (axis cs:{BBAR},{thr});
\draw[dotted, gray] (axis cs:0,{RHO}) -- (axis cs:{BBAR},{RHO});
% sticky boundaries: full on the right (filling modes), empty on the left (draining modes)
\draw[line width=2.2pt, verdecito!80!black] (axis cs:{BBAR},0) -- (axis cs:{BBAR},{thr});
\draw[line width=2.2pt, rojito] (axis cs:0,{thr}) -- (axis cs:0,1);
% vector field
\addplot[gray!60, -stealth, quiver={{u=\thisrowno{{2}}, v=\thisrowno{{3}}}}] table[row sep=newline] {{
{qrows}
}};
{chr(10).join(trajs)}
% equilibrium
\node[circle, draw=black, fill=yellow!80!orange, inner sep=2.6pt, line width=0.8pt] at (axis cs:{xeq},{neq}) {{}};
{eqnode}
{extra}
\end{{axis}}
\end{{tikzpicture}}
"""
    open(os.path.join(OUT, fname), "w").write(body)
    print(fname, "equilibrium (x, n) =", (xeq, neq), "threshold", thr)


if __name__ == "__main__":
    # over-provisioned: pbar > c rho = 0.25
    panel(0.36, [(0.9, 0.10), (0.6, 0.17), (0.05, 0.03), (0.15, 0.17), (0.95, 0.025)],
          "phase_over.tex", r"Over-provisioned, $\bar p > c\rho$")
    # under-provisioned: pbar < c rho
    panel(0.17, [(0.05, 0.19), (0.02, 0.06), (0.4, 0.17), (0.85, 0.12), (0.78, 0.07)],
          "phase_under.tex", r"Under-provisioned, $\bar p < c\rho$")
